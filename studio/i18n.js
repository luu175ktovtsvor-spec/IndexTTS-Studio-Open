  function indexStatic(root = document.body) {
    if (indexed || !root) return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
      if (node.parentElement?.closest("script,style,code")) continue;
      const raw = node.nodeValue.trim();
      const key = reverse[raw] || normalizedSources[normalizeSource(raw)];
      if (!raw || !key || !catalogs.en[key]) continue;
      textNodes.push({ node, key, original: node.nodeValue });
    }
    root
      .querySelectorAll("[placeholder],[aria-label],[title]")
      .forEach((element) => {
        ["placeholder", "aria-label", "title"].forEach((name) => {
          const key = element.getAttribute(name);
          if (key && catalogs.en[key]) attributes.push({ element, name, key });
        });
      });
    indexed = true;
  }

  function refreshLiveText() {
    document.querySelectorAll("[data-i18n-key]").forEach((element) => {
      let vars = {};
      try {
        vars = JSON.parse(element.dataset.i18nVars || "{}");
      } catch {
        vars = {};
      }
      element.textContent = t(element.dataset.i18nKey, vars);
    });
  }

  function apply(locale, persist = true) {
    if (!localeNames[locale]) locale = "zh";
    current = locale;
    indexStatic();
    textNodes.forEach(({ node, key, original }) => {
      const prefix = original.match(/^\s*/)?.[0] || "";
      const suffix = original.match(/\s*$/)?.[0] || "";
      node.nodeValue = prefix + t(key) + suffix;
    });
    attributes.forEach(({ element, name, key }) =>
      element.setAttribute(name, t(key)),
    );
    refreshLiveText();
    document.title = t(documentTitleSource);
    document.documentElement.lang = languageTags[locale];
    document.documentElement.dir = locale === "ar" ? "rtl" : "ltr";
    document.body?.classList.toggle("rtl-ui", locale === "ar");
    if (persist) {
      try {
        localStorage.setItem("index-tts-ui-locale", locale);
      } catch {
        // Language switching still works when browser storage is unavailable.
      }
    }
    listeners.forEach((listener) => listener(locale));
  }

  function setText(elementOrId, source, vars = {}) {
    const element =
      typeof elementOrId === "string"
        ? document.getElementById(elementOrId)
        : elementOrId;
    if (!element) return;
    element.dataset.i18nKey = source;
    element.dataset.i18nVars = JSON.stringify(vars);
    element.textContent = t(source, vars);
  }

  function onChange(listener) {
    listeners.add(listener);
    return () => listeners.delete(listener);
  }

